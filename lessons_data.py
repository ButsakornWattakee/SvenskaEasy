for lesson in LESSONS:
    l_id = lesson["id"]
    if l_id in PRACTICE_DATA:
        lesson["typing_practice"] = PRACTICE_DATA[l_id]["typing"]
        lesson["matching_practice"] = PRACTICE_DATA[l_id]["matching"]

# DYNAMIC DETAILED VOCABULARY TABLES GENERATION WITH PRONUNCIATION
for lesson in LESSONS:
    l_id = lesson["id"]
    vocab_map = {}
    
    if "typing_practice" in lesson:
        for tp in lesson["typing_practice"]:
            sw = tp["swedish"]
            clue = tp.get("clue", sw)
            # Extract bracketed clue if present
            pron_str = clue.split("[")[-1].replace("]", "") if "[" in clue else clue
            thai_cleaned = tp["thai"].split(" (")[0].strip()
            vocab_map[sw] = {
                "swedish": sw,
                "pronunciation": pron_str,
                "thai": thai_cleaned,
                "explanation": tp["explanation"]
            }
            
    if "matching_practice" in lesson:
        for mp in lesson["matching_practice"]:
            sw = mp["swedish"]
            thai_clean = mp["thai"].split(" (")[0].strip()
            pron_str = mp["thai"].split("[")[-1].replace("])", "").replace("]", "") if "[" in mp["thai"] else sw
            if sw not in vocab_map:
                vocab_map[sw] = {
                    "swedish": sw,
                    "pronunciation": pron_str,
                    "thai": thai_clean,
                    "explanation": "คำศัพท์หลักประจำบทเรียนสำหรับการฝึกฝนและสนทนา"
                }

    if vocab_map:
        md_table = "\n\n| คำศัพท์ภาษาสวีเดน (Swedish) | คำอ่านภาษาไทย (Pronunciation) | คำแปลภาษาไทย (Thai) | คำอธิบาย / การใช้งาน (Description) |\n"
        md_table += "| :--- | :--- | :--- | :--- |\n"
        for sw, item in sorted(vocab_map.items()):
            md_table += f"| **{item['swedish']}** | [{item['pronunciation']}] | {item['thai']} | {item['explanation']} |\n"
            
        lesson["sections"].append({
            "subtitle": "ตารางสรุปคำศัพท์ คำอ่าน และสำนวนสำคัญประจำบท (Key Vocabulary & Phonetics)",
            "content": md_table
        })
